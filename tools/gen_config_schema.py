#!/usr/bin/env python3
"""Regenerate config.schema.json from the shipped configuration files.

The schema mirrors the structure of config.yml (plus any extra key used by the
difficulty presets): section names are closed, so a misspelt section is
reported, while value types are checked wherever the defaults define them.

Usage: python tools/gen_config_schema.py [--check]
"""

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / 'config.schema.json'
BASE = 'config.yml'
OVERRIDES = ('config_easy.yml', 'config_hard.yml', 'config_hell.yml', 'hardmode.yml', 'config.sample.yml')


def merge_shapes(base, extra):
    """Union of two config trees, used only to learn which keys exist."""
    if isinstance(base, dict) and isinstance(extra, dict):
        merged = dict(base)
        for key, value in extra.items():
            merged[key] = merge_shapes(merged[key], value) if key in merged else value
        return merged
    return base


def scalar_schema(value):
    if isinstance(value, bool):
        return {'type': 'boolean'}
    if isinstance(value, (int, float)):
        return {'type': 'number'}
    if isinstance(value, str):
        return {'type': 'string'}
    return {}


def common_schema(schemas):
    """The schema shared by every item, or 'anything' when they differ."""
    schemas = [s for s in schemas]
    if schemas and all(s == schemas[0] for s in schemas):
        return schemas[0]
    types = {s.get('type') for s in schemas}
    return {'type': types.pop()} if len(types) == 1 and None not in types else {}


def schema_for(value):
    if isinstance(value, dict):
        if all(isinstance(key, str) for key in value):
            return {
                'type': 'object',
                'properties': {key: schema_for(item) for key, item in value.items()},
            }
        # Tables keyed by tier or level number
        return {'type': 'object', 'additionalProperties': common_schema([schema_for(v) for v in value.values()])}
    if isinstance(value, list):
        return {'type': 'array', 'items': common_schema([schema_for(v) for v in value])}
    return scalar_schema(value)


def build():
    shape = yaml.safe_load((ROOT / BASE).read_text(encoding='utf-8'))
    for name in OVERRIDES:
        path = ROOT / name
        if path.exists():
            shape = merge_shapes(shape, yaml.safe_load(path.read_text(encoding='utf-8')) or {})
    schema = schema_for(shape)
    return {
        '$schema': 'http://json-schema.org/draft-07/schema#',
        'title': 'BVB configuration',
        'description': 'Generated by tools/gen_config_schema.py from config.yml - do not edit by hand.',
        'type': 'object',
        'properties': schema['properties'],
        'additionalProperties': False,
    }


def main():
    text = json.dumps(build(), indent=2, sort_keys=True) + '\n'
    if '--check' in sys.argv:
        if SCHEMA.read_text(encoding='utf-8') != text:
            sys.exit('config.schema.json is out of date: run python tools/gen_config_schema.py')
        return
    SCHEMA.write_text(text, encoding='utf-8')
    print(f'wrote {SCHEMA.name}')


if __name__ == '__main__':
    main()
